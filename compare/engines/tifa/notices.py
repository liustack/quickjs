"""Generate THIRD_PARTY_NOTICES.md from matching tifa builds and npm metadata.

python3 notices.py /path/to/tifa
Reads installed packages and source maps without building or installing.
Fetches locked FormatJS tarballs only for their metadata and license files.
"""
import base64
import hashlib
import io
import json
from pathlib import Path
import re
import sys
import tarfile
import urllib.request

HERE = Path(__file__).resolve().parent
APPS = {'bench': 'test/apps/bench', 'mui': 'test/apps/mui', 'shop': 'examples/shop'}
# This npm tarball omits its license. Keep the upstream project's license
# at an immutable commit, and disclose that separate source in the notice.
SOURCE_LICENSES = {
    ('react-remove-scroll-bar', '2.3.8'): (
        'https://raw.githubusercontent.com/theKashey/react-remove-scroll-bar/'
        '8ca9ba5ea52de03308fe8ced94f7b159a44d28ff/LICENSE'),
}


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def is_notice(name):
    return bool(re.match(r'^(licen[cs]e|notice|copying|copyright)', name, re.I))


def generate(root):
    packages = {}
    provenance = []

    def add(meta, texts, app):
        key = (meta['name'], meta['version'])
        if not texts:
            url = SOURCE_LICENSES[key]  # Missing material is an error.
            texts = [(url, fetch(url).decode())]
        entry = packages.setdefault(key, {'license': meta['license'], 'texts': texts, 'apps': set()})
        assert entry['license'] == meta['license'], key
        assert [t for _, t in entry['texts']] == [t for _, t in texts], key
        entry['apps'].add(app)

    for app, rel in APPS.items():
        base = root / rel
        bundle = (base / '.tifa/dist/ssr.js').read_bytes()
        assert bundle == (HERE / 'bundles' / (app + '.js')).read_bytes(), app + ': bundle differs'
        source_map = (base / '.tifa/dist/ssr.js.map').read_bytes()
        provenance.append((app, sha(bundle), sha(source_map), sha((base / 'pnpm-lock.yaml').read_bytes())))
        seen = set()
        for source in json.loads(source_map)['sources']:
            if 'node_modules/' not in source:
                continue
            prefix, suffix = source.rsplit('node_modules/', 1)
            name = '/'.join(suffix.split('/')[:2]) if suffix.startswith('@') else suffix.split('/')[0]
            package = base / (prefix + 'node_modules/' + name)
            if package in seen:
                continue
            seen.add(package)
            meta = json.loads((package / 'package.json').read_text())
            assert meta['name'] == name, source
            texts = [(p.name, p.read_text()) for p in sorted(package.iterdir()) if p.is_file() and is_notice(p.name)]
            add(meta, texts, app)

    lock_bytes = (HERE / 'polyfill/package-lock.json').read_bytes()
    lock = json.loads(lock_bytes)['packages']
    # Follow the runtime dependency closure, excluding esbuild and its platform
    # executables. They build the script but do not appear in it.
    pending = [n for n in lock['']['dependencies'] if n != 'esbuild']
    seen = set()
    while pending:
        name = pending.pop()
        if name in seen:
            continue
        seen.add(name)
        item = lock['node_modules/' + name]
        data = fetch(item['resolved'])
        algorithm, expected = item['integrity'].split('-', 1)
        assert base64.b64encode(hashlib.new(algorithm, data).digest()).decode() == expected, name
        with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as tar:
            meta = json.load(tar.extractfile('package/package.json'))
            assert (meta['name'], meta['version'], meta['license']) == (name, item['version'], item['license']), name
            texts = [(m.name.removeprefix('package/'), tar.extractfile(m).read().decode())
                     for m in sorted(tar.getmembers(), key=lambda m: m.name)
                     if m.isfile() and len(Path(m.name).parts) == 2 and is_notice(Path(m.name).name)]
        add(meta, texts, 'polyfill')
        pending.extend(item.get('dependencies', {}))

    lines = ['<!-- Copyright (c) 2026 The liustack/quickjs Authors. -->',
             '<!-- SPDX-License-Identifier: MIT -->',
             '<!-- The generator and inventory are MIT under LICENSE-MIT at the repository root. -->',
             '<!-- The copied third-party notices below retain their own terms. -->', '',
             '# tifa bundle third-party notices', '',
             'Generated by `python3 compare/engines/tifa/notices.py /path/to/tifa`.',
             'The three source bundles must match the committed files byte for byte.',
             'Their source maps identify the npm packages. Names, versions and licenses',
             'come from those installed packages, with their license and notice files copied below.',
             'Identical texts share a section. Line-end whitespace is omitted.', '',
             'The polyfill rows cover the runtime dependency closure in',
             '`polyfill/package-lock.json`. Metadata and notices come from the tarballs',
             'at its resolved URLs, checked against its integrity hashes. esbuild is a',
             'build tool, not bundled code. The polyfill itself is not committed.', '',
             'The tifa app and runtime code is MIT. Its license is included below.',
             'react-remove-scroll-bar omits a license file from its npm package.',
             'Its metadata declares MIT. The text below comes from its upstream project',
             'at commit `8ca9ba5ea52de03308fe8ced94f7b159a44d28ff`, where LICENSE was added.', '',
             '## Source fingerprints', '',
             '| Bundle | SHA256 | Source map SHA256 | App lockfile SHA256 |',
             '| --- | --- | --- | --- |']
    for row in provenance:
        lines.append('| ' + ' | '.join(row) + ' |')
    lines += ['', 'Polyfill lockfile SHA256: `' + sha(lock_bytes) + '`.', '', '## Packages', '',
              '| Package | Version | License | Bundles | Texts |', '| --- | --- | --- | --- | --- |']
    notices = {}
    def reference(text):
        cleaned = '\n'.join(line.rstrip() for line in text.splitlines()).strip() + '\n'
        if cleaned not in notices:
            notices[cleaned] = len(notices) + 1
        return notices[cleaned]
    tifa_ref = reference((root / 'LICENSE').read_text())
    for (name, version), row in sorted(packages.items()):
        refs = ', '.join(f'[{filename}](#text-{reference(text)})' for filename, text in row['texts'])
        lines.append(f"| {name} | {version} | {row['license']} | {', '.join(sorted(row['apps']))} | {refs} |")
    lines += ['', f'tifa source license: [text {tifa_ref}](#text-{tifa_ref}).']
    for text, number in notices.items():
        lines += ['', f'## Text {number}', '', '```text', text.rstrip(), '```']
    return '\n'.join(lines).rstrip() + '\n'


if __name__ == '__main__':
    root = Path(sys.argv[1]).resolve()
    output = generate(root)
    (HERE / 'THIRD_PARTY_NOTICES.md').write_text(output)
