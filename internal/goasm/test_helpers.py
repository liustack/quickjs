import unittest
import helpers

class HelpersTests(unittest.TestCase):
 def test_sorted_unique_after_header(self):
  lines=helpers.text(['set_value','get_shape_prop','set_value']).splitlines()
  body=[l for l in lines if not l.startswith('#')]
  self.assertTrue(lines[0].startswith('# Generated by internal/goasm/build.py'))
  self.assertEqual(body,['get_shape_prop','set_value'])
 def test_rejects_names_that_are_not_c(self):
  with self.assertRaises(ValueError):helpers.text(['ok','not ok'])
 def test_rejects_empty(self):
  with self.assertRaises(ValueError):helpers.text([])

if __name__=='__main__':unittest.main()
