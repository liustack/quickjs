"""Generate fixed SysV to ABI0 bridges from Clang and Go signatures."""
import json,pathlib,sys

def typ(c):
 if '*' in c or c in ('uintptr_t','size_t'):return 'uintptr'
 if c=='JSValue':return 'TJSValue'
 if c in ('double',):return 'float64'
 if c in ('int','BOOL','int32_t'):return 'int32'
 if c in ('JSAtom','uint32_t','OPCodeEnum'):return 'uint32'
 if c=='void':return ''
 raise ValueError(c)
# SysV callee-saved registers other than RBP, which Go's frame keeps.
# Go clobbers all of them, and its ABI wrappers load g into R14.
SAVED=['BX','R12','R13','R14','R15']
# Offset of the 48 bytes for varargs in goasm_args (see prepare.py).
VARARGS=136
# Sizes of the Go types of engine functions a bridge may call directly.
GOSIZE={'uintptr':8,'TJSValue':16,'int32':4,'uint32':4,'TJSAtom':4,'TBOOL':4,'TOPCodeEnum':4,'Size_t':8,'Tuint32_t':4,'float64':8}
def size(t):return {'uintptr':8,'TJSValue':16,'float64':8,'int32':4,'uint32':4,'':0}[t]
def align(x,a):return (x+a-1)//a*a

def generate(registry,signatures,out):
 go=['// Copyright (c) 2026 The slowjs Authors.','// SPDX-License-Identifier: MIT','// See LICENSE-MIT at the repository root.','// Code generated by internal/goasm. DO NOT EDIT.','//go:build goasm && linux && amd64','package libquickjs','import("unsafe";"modernc.org/libc")']
 asm=['// Copyright (c) 2026 The slowjs Authors.','// SPDX-License-Identifier: MIT','// See LICENSE-MIT at the repository root.','// Code generated by internal/goasm. DO NOT EDIT.','//go:build goasm && linux && amd64','','#include "textflag.h"','#include "funcdata.h"']
 for b in registry:
  ident=str(b['id']); ts=['uintptr']+[typ(t) for t in b['args']];rt=typ(b['ret'])
  decl=', '.join('a%d %s'%(i,t) for i,t in enumerate(ts))
  body=['tls:=*(**libc.TLS)(unsafe.Pointer(a0))'];direct=None
  if b['kind']=='indirect':
   ft='func(*libc.TLS,'+','.join(ts[2:])+') '+rt
   call='(*(*'+ft+')(unsafe.Pointer(&struct{p uintptr}{a1})))(tls,'+','.join('a%d'%i for i in range(2,len(ts)))+')'
  else:
   names=['_'+b['name'],'X'+b['name'],'x'+b['name']]
   # A javascript call from the interpreter enters the interpreter again:
   # skip the ccgo function, whose only work here is to call goasmCall.
   if b['name']=='JS_CallInternal':names=['goasmCall']
   matches=[(k,v) for k,v in signatures.items() if k.split(':')[-1] in names]
   if len(matches)!=1:raise ValueError((b,matches))
   key,sig=matches[0];name=key.split(':')[-1]
   if key.startswith('modernc.org/libc:'):name='libc.'+name
   ps=sig['Params'][1:];args=['tls']
   if b['kind']=='varargs':
    fixed=len(ps)-1
    if len(ts)-fixed-1>6 or any(size(t)>8 for t in ts[fixed+1:]):
     raise ValueError('varargs exceed the 48-byte external scratch area')
    for i,t in enumerate(ps[:fixed],1):args.append(t+'(a%d)'%i)
    body.append('va:=a0+%d'%VARARGS)
    for i,t in enumerate(ts[fixed+1:]):body.append('*(*'+t+')(unsafe.Pointer(va+%d))=a%d'%(8*i,fixed+1+i))
    args.append('va')
   else:
    if len(ps)!=len(ts)-1:raise ValueError((b,sig))
    args += [t+'(a%d)'%i for i,t in enumerate(ps,1)]
    # A function of this package takes the same ABI0 frame as its bridge,
    # with the TLS in place of the env: call it without the Go bridge.
    res=sig['Results'] or []
    if key.startswith('github.com/liustack/slowjs/lib:') and all(GOSIZE.get(g)==size(t) for g,t in zip(ps,ts[1:])) and \
       ([GOSIZE.get(r) for r in res]==([size(rt)] if rt else [])):
     direct=name
   call=name+'('+','.join(args)+')'
  body.append(('return '+rt+'('+call+')') if rt else call)
  if not direct:go.append('func goasmBridge'+ident+'('+decl+') '+rt+' {\n'+'\n'.join(body)+'\n}')
  # Each Go argument is naturally aligned. SysV aggregates use two integer
  # registers atomically, or go wholly to the caller's stack.
  offsets=[];off=0
  for t in ts:off=align(off,min(size(t),8));offsets.append(off);off+=size(t)
  retpos=align(off,8);saved=align(retpos+size(rt),8);frame=align(saved+8*len(SAVED),16)
  asm+=['TEXT ·goasm_c_'+ident+'(SB), NOSPLIT, $%d-0'%frame,'NO_LOCAL_POINTERS']
  for i,r in enumerate(SAVED):asm.append('MOVQ %s, %d(SP)'%(r,saved+i*8))
  regs=['DI','SI','DX','CX','R8','R9'];nr=0;nx=0;stack=0
  for t,dest in zip(ts,offsets):
   words=(size(t)+7)//8
   if direct and dest==0:asm+=['MOVQ 0(DI), AX','MOVQ AX, 0(SP)'];nr+=1
   elif t=='float64' and nx<8:asm.append('MOVSD X%d, %d(SP)'%(nx,dest));nx+=1
   elif t!='float64' and nr+words<=6:
    for w in range(words):asm.append('%s %s, %d(SP)'%('MOVL' if size(t)==4 else 'MOVQ',regs[nr+w],dest+w*8))
    nr+=words
   else:
    for w in range(words):
     ins='MOVL' if size(t)==4 else 'MOVQ'
     asm+=['%s %d(SP), AX'%(ins,frame+16+stack+w*8),'%s AX, %d(SP)'%(ins,dest+w*8)]
    stack+=words*8
  asm.append('CALL ·'+(direct or 'goasmBridge'+ident)+'(SB)')
  if rt=='TJSValue':asm+=['MOVQ %d(SP), AX'%retpos,'MOVQ %d(SP), DX'%(retpos+8)]
  elif rt:asm.append('%s %d(SP), %s'%('MOVSD' if rt=='float64' else 'MOVL' if size(rt)==4 else 'MOVQ',retpos,'X0' if rt=='float64' else 'AX'))
  for i,r in enumerate(SAVED):asm.append('MOVQ %d(SP), %s'%(saved+i*8,r))
  asm.append('RET')
 out.mkdir(exist_ok=True)
 (out/'goasm_bridges_linux_amd64.go').write_text('\n'.join(go)+'\n')
 asm += ['TEXT ·goasm_alloca(SB), NOSPLIT, $64-0','NO_LOCAL_POINTERS']
 for i,r in enumerate(SAVED):asm.append('MOVQ %s, %d(SP)'%(r,24+i*8))
 asm += ['MOVQ DI, 0(SP)','MOVQ SI, 8(SP)','CALL ·goasmAllocate(SB)','MOVQ 16(SP), AX']
 for i,r in enumerate(SAVED):asm.append('MOVQ %d(SP), %s'%(24+i*8,r))
 asm += ['RET']
 # goasm_reenter(env, locals) runs a new interpreter frame: the Go entry of
 # goasmRun checks the goroutine stack and grows it when needed.
 asm += ['TEXT ·goasm_reenter(SB), NOSPLIT, $64-0','NO_LOCAL_POINTERS']
 for i,r in enumerate(SAVED):asm.append('MOVQ %s, %d(SP)'%(r,24+i*8))
 asm += ['MOVQ 0(DI), AX','MOVQ AX, 0(SP)','MOVQ DI, 8(SP)','MOVQ SI, 16(SP)','CALL ·goasmRun(SB)']
 for i,r in enumerate(SAVED):asm.append('MOVQ %d(SP), %s'%(24+i*8,r))
 asm += ['RET']
 (out/'goasm_bridges_linux_amd64.s').write_text('\n'.join(asm)+'\n')
if __name__=='__main__':generate(json.load(open(sys.argv[1])),json.load(open(sys.argv[2])),pathlib.Path(sys.argv[3]))
