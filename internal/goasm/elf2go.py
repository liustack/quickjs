"""Emit resolved local code bytes and symbolic Go CALLs from ELF64."""
import struct,json,pathlib,sys
b=pathlib.Path(sys.argv[1]).read_bytes()
assert b[:6]==b'\x7fELF\x02\x01'
shoff=struct.unpack_from('<Q',b,40)[0];shsize,shnum,shstr=struct.unpack_from('<HHH',b,58)
sh=[struct.unpack_from('<IIQQQQIIQQ',b,shoff+i*shsize) for i in range(shnum)]
def data(s):return b[s[4]:s[4]+s[5]]
def string(tab,n):return tab[n:tab.index(b'\0',n)].decode()
names=data(sh[shstr]);idx=next(i for i,s in enumerate(sh) if string(names,s[0])=='.text');code=data(sh[idx]);calls={}
for s in sh:
 if s[1]!=4 or s[7]!=idx:continue
 syms=sh[s[6]];strings=data(sh[syms[6]])
 for p in range(s[4],s[4]+s[5],24):
  off,info,add=struct.unpack_from('<QQq',b,p);sym=struct.unpack_from('<IBBHQQ',b,syms[4]+(info>>32)*24);name=string(strings,sym[0])
  assert (info&0xffffffff)==4 and add==-4 and code[off-1]==0xe8,(off,name,info,add)
  assert name.startswith('goasm_c_') or name in ('goasm_alloca','goasm_reenter'),name
  calls[off-1]=name
frame=json.load(open(sys.argv[2]))['frame']
out=['// Copyright (c) 2026 The slowjs Authors.','// SPDX-License-Identifier: MIT','// See LICENSE-MIT at the repository root.','// Interpreter code follows QuickJS by Fabrice Bellard and Charlie Gordon.', '// See LICENSE-LIBQUICKJS for its MIT license.','// Code generated by internal/goasm. DO NOT EDIT.','//go:build goasm && linux && amd64','','#include "textflag.h"','#include "funcdata.h"',f'TEXT ·goasmRun(SB), $%d-24'%frame,'NO_LOCAL_POINTERS','PCALIGN $16']
i=0
while i<len(code):
 if i in calls:out.append('CALL ·'+calls[i]+'(SB)');i+=5;continue
 stop=min([p for p in calls if p>i]+[len(code)])
 if stop-i>=8:out.append('QUAD $0x'+code[i:i+8][::-1].hex());i+=8
 else:out.append('BYTE $0x%02x'%code[i]);i+=1
out.append('RET')
pathlib.Path(sys.argv[3]).write_text('\n'.join(out)+'\n')
print(len(code),'bytes',len(calls),'calls','frame',frame)
