// TestGoCallsList fails when internal/cengine/gocalls.txt is not the list
// GoCalls makes from the Go sources: Go code names an engine function the
// list does not hold (its result would not reach Go), or the list holds one
// Go no longer names (it writes a result nobody reads).
func TestGoCallsList(t *testing.T) {
	root := filepath.Join("..", "..", "..")
	pkg := filepath.Join(root, "internal", "cengine")
	got, err := GoCalls(root, pkg)
	if err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(pkg, GoCallsFile))
	if err != nil {
		t.Fatal(err)
	}
	list, err := ReadGoCalls(b)
	if err != nil {
		t.Fatal(err)
	}
	var missing, stale []string
	for _, n := range got {
		if !list[n] {
			missing = append(missing, n)
		}
	}
	for _, n := range SortedKeys(list) {
		if !slices.Contains(got, n) {
			stale = append(stale, n)
		}
	}
	if len(missing) > 0 || len(stale) > 0 {
		t.Errorf("internal/cengine/%s is stale (run go run ./internal/goasm/gen/cmd/gocalls, then make gen and make gen ARCH=arm64): Go code names %v, which the list does not hold, and no longer names %v", GoCallsFile, missing, stale)
	}
	if string(b) != string(SortGoCalls(got)) {
		t.Errorf("internal/cengine/%s is not in the form cmd/gocalls writes", GoCallsFile)
	}
}

// TestGoCalls runs GoCalls over a small module: what counts as Go naming a
// function of the engine, and what does not.
func TestGoCalls(t *testing.T) {
	root := t.TempDir()
	write := func(name, src string) {
		t.Helper()
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	var decl strings.Builder
	decl.WriteString("// Code generated by internal/goasm/gen. DO NOT EDIT.\n\npackage eng\n\n")
	fns := []string{"Called", "Value", "InTest", "Ext", "ExtTest", "Renamed", "Nested", "FromAsm", "InClosure",
		"Shadowed", "Param", "Field", "Key", "Imported", "Local", "Range", "TypeSw", "Never", "Skipped", "Wrapper_go",
		"Macro", "OtherAsm", "Linked", "GenOut"}
	for _, f := range fns {
		decl.WriteString("func " + f + "(sp uintptr) uint64\n")
	}
	write("go.mod", "module example.com/m\n\ngo 1.26\n")
	write("internal/eng/engine_decl_amd64.go", decl.String())
	write("internal/eng/engine_decl_arm64.go", "// Code generated by internal/goasm/gen. DO NOT EDIT.\n\npackage eng\n\nfunc OnlyArm(sp uintptr) uint64\n")
	write("internal/eng/engine_keep_amd64.go", "// Code generated by internal/goasm/gen. DO NOT EDIT.\n\npackage eng\n\nvar keep = []any{Never, Skipped}\n")
	write("internal/eng/vm.go", `package eng

import Imported "strings"

type T struct{ Field int }

func f(Param int) {
	_ = Called(0)
	g := Value
	_ = g
	func() { _ = InClosure(0) }()
	Shadowed := 1
	_ = Shadowed
	_ = Param
	_ = T{Field: 1}
	_ = map[string]int{"Key": 1}
	_ = Imported.ToUpper("")
	var Local int
	_ = Local
	for Range := range 3 {
		_ = Range
	}
	var x any
	switch TypeSw := x.(type) {
	default:
		_ = TypeSw
	}
	if OnlyArm(0) == 0 {
	}
	_ = Wrapper_go(0)
}
`)
	write("internal/eng/vm_test.go", "package eng\n\nfunc init() { InTest(0) }\n")
	write("internal/eng/ext_test.go", "package eng_test\n\nimport e \"example.com/m/internal/eng\"\n\nvar _ = e.ExtTest(0)\n")
	write("internal/eng/glue.s", "TEXT ·glue(SB), 0, $0-0\n\tCALL ·FromAsm(SB)\n\tRET\n")
	write("internal/eng/macro.s", "#define T ·Macro\nTEXT ·m(SB), 0, $0-0\n\tCALL T(SB)\n\tRET\n")
	write("other/o_amd64.s", "TEXT ·o(SB), 0, $0-0\n\tCALL example.com∕m∕internal∕eng·OtherAsm(SB)\n\tRET\n")
	write("other/link.go", "package other\n\nimport _ \"unsafe\"\n\n//go:linkname linked example.com/m/internal/eng.Linked\nfunc linked(sp uintptr) uint64\n")
	write("other/gen.go", "// Code generated by hand. DO NOT EDIT.\n\npackage other\n\nimport \"example.com/m/internal/eng\"\n\nvar _ = eng.GenOut\n")
	write("internal/eng/gen_amd64.s", "// Code generated by internal/goasm/gen. DO NOT EDIT.\n\nTEXT ·x(SB), 0, $0-0\n\tCALL ·Skipped(SB)\n")
	write("api.go", "package m\n\nimport (\n\t\"example.com/m/internal/eng\"\n\tren \"example.com/m/internal/eng\"\n)\n\nvar _ = eng.Ext(0) + ren.Renamed(0)\n")
	write("sub/go.mod", "module example.com/m/sub\n\ngo 1.26\n")
	write("sub/s.go", "package sub\n\nimport \"example.com/m/internal/eng\"\n\nvar _ = eng.Nested(0)\n")
	write("testdata/t.go", "package t\n\nimport \"example.com/m/internal/eng\"\n\nvar _ = eng.Never(0)\n")
	write(".hidden/h.go", "package h\n\nimport \"example.com/m/internal/eng\"\n\nvar _ = eng.Never(0)\n")
	write("other/o.go", "package other\n\nfunc Called() {}\n\nvar _ = Skipped\n\nvar Skipped = 1\n")

	got, err := GoCalls(root, filepath.Join(root, "internal", "eng"))
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"Called", "Ext", "ExtTest", "FromAsm", "GenOut", "InClosure", "InTest", "Linked", "Macro", "Nested", "OnlyArm", "OtherAsm", "Renamed", "Value", "Wrapper_go"}
	if !slices.Equal(got, want) {
		t.Errorf("GoCalls = %v, want %v", got, want)
	}

	b := SortGoCalls(got)
	back, err := ReadGoCalls(b)
	if err != nil || !slices.Equal(SortedKeys(back), want) {
		t.Errorf("ReadGoCalls(SortGoCalls) = %v, %v", SortedKeys(back), err)
	}
	if _, err := ReadGoCalls([]byte("a b\n")); err == nil {
		t.Error("ReadGoCalls takes a line that is no Go name")
	}
}
