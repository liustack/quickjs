// asmFunc is one TEXT of a generated .s file: its frame and the runs of
// machine code it writes as bytes, each run between two lines the Go
// assembler writes itself (a CALL, a LEAQ of a symbol, a move by name).
type asmFunc struct {
	name  string
	frame int
	runs  [][]byte
}

var (
	reAsmText = regexp.MustCompile(`^TEXT ·(\w+)\(SB\), (?:[A-Z|]+, )?\$(\d+)-\d+$`)
	reAsmRaw  = regexp.MustCompile(`^\t(QUAD|WORD|BYTE) \$0x([0-9a-f]+)(?: //.*)?$`)
)

// readAsmFuncs reads the functions of the generated .s files of arch in
// internal/cengine. The data after the code of a function, which starts at
// the comment emitData writes, is not machine code and is left out.
func readAsmFuncs(t *testing.T, arch string) []asmFunc {
	t.Helper()
	files, err := filepath.Glob(filepath.Join("..", "..", "cengine", "*_"+arch+".s"))
	if err != nil || len(files) == 0 {
		t.Fatalf("no generated .s files of %s: %v", arch, err)
	}
	var fns []asmFunc
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.HasPrefix(string(b), "// Code generated by internal/goasm/gen.") {
			continue
		}
		var cur *asmFunc
		var run []byte
		inData := false
		end := func() {
			if cur != nil && len(run) > 0 {
				cur.runs = append(cur.runs, run)
			}
			run = nil
		}
		for _, l := range strings.Split(string(b), "\n") {
			if m := reAsmText.FindStringSubmatch(l); m != nil {
				end()
				fr, _ := strconv.Atoi(m[2])
				fns = append(fns, asmFunc{name: m[1], frame: fr})
				cur, inData = &fns[len(fns)-1], false
				continue
			}
			if l == dataComment {
				end()
				inData = true
				continue
			}
			m := reAsmRaw.FindStringSubmatch(l)
			if m == nil {
				end()
				continue
			}
			if inData {
				continue
			}
			v, err := strconv.ParseUint(m[2], 16, 64)
			if err != nil {
				t.Fatalf("%s: %q: %v", f, l, err)
			}
			switch m[1] {
			case "QUAD":
				run = binary.LittleEndian.AppendUint64(run, v)
			case "WORD":
				run = binary.LittleEndian.AppendUint32(run, uint32(v))
			case "BYTE":
				run = append(run, byte(v))
			}
		}
		end()
	}
	return fns
}

// TestEngineArgsByName: the generated engine reads its arguments and writes
// its results only by name through FP, which is all Go promises about where
// they are, and never at an offset from SP that depends on how the
// assembler lays out a frame. So no instruction the generator writes as
// bytes reaches past the locals of its frame: on amd64 an access at
// N(SP) with N at or above the frame of the TEXT, on arm64 at or above the
// frame and the saved LR. Every word of an arm64 function's code is one
// instruction, and a word that does not decode is data of llc's (a jump table
// in the code is copied as it is), so only the ones that decode are looked at.
func TestEngineArgsByName(t *testing.T) {
	for _, arch := range []string{"amd64", "arm64"} {
		t.Run(arch, func(t *testing.T) {
			bad, n := 0, 0
			report := func(fn asmFunc, what string) {
				if bad++; bad <= 10 {
					t.Errorf("%s (frame %d): %s", fn.name, fn.frame, what)
				}
			}
			for _, fn := range readAsmFuncs(t, arch) {
				n++
				for _, run := range fn.runs {
					if arch == "amd64" {
						for i := 0; i < len(run); {
							in, err := x86asm.Decode(run[i:], 64)
							if err != nil {
								report(fn, fmt.Sprintf("bytes at %d of a run do not decode: %v", i, err))
								break
							}
							for _, a := range in.Args {
								if m, ok := a.(x86asm.Mem); ok && m.Base == x86asm.RSP && m.Disp >= int64(fn.frame) {
									report(fn, fmt.Sprintf("%v, written as bytes, reaches %d(SP), past the frame", in, m.Disp))
								}
							}
							i += in.Len
						}
						continue
					}
					for i := 0; i+4 <= len(run); i += 4 {
						in, err := arm64asm.Decode(run[i:])
						if err != nil {
							continue
						}
						for _, a := range in.Args {
							if d, ok := a64SPOffset(a); ok && d >= fn.frame+8 {
								report(fn, fmt.Sprintf("%v, written as a word, reaches %d(RSP), past the frame and LR", in, d))
							}
						}
					}
				}
			}
			if n < 1000 {
				t.Fatalf("only %d functions in the generated files of %s", n, arch)
			}
			if bad > 0 {
				t.Fatalf("%d instructions of %d functions reach the argument area from SP", bad, n)
			}
		})
	}
}

var reA64MemSPArg = regexp.MustCompile(`^\[SP(?:,#(-?\d+))?\]$`)

// a64SPOffset gives the offset of an arm64 memory operand based on SP with an
// immediate offset and no write back.
func a64SPOffset(a arm64asm.Arg) (int, bool) {
	m, ok := a.(arm64asm.MemImmediate)
	if !ok || m.Base != arm64asm.RegSP(arm64asm.SP) {
		return 0, false
	}
	s := reA64MemSPArg.FindStringSubmatch(m.String())
	if s == nil {
		return 0, false
	}
	d, _ := strconv.Atoi(s[1])
	return d, true
}

// TestEngineAsmDecl runs go vet's check of the assembly over the generated
// engine for each system: every argument and result the assembly names
// must be the one of its Go declaration, at its offset and of its size,
// every function with a result writes it, and every function with a frame
// has a Go declaration. It reports nothing: the register-entry leaves of
// amd64 say NOFRAME, and goasm_room is in a file of windows/amd64 only, as
// its declaration is.
func TestEngineAsmDecl(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go vet")
	}
	for _, target := range []string{"linux/amd64", "windows/amd64", "darwin/amd64", "linux/arm64", "darwin/arm64"} {
		goos, goarch, _ := strings.Cut(target, "/")
		cmd := exec.Command("go", "vet", "-asmdecl", "./internal/cengine")
		cmd.Dir = filepath.Join("..", "..", "..")
		cmd.Env = append(os.Environ(), "GOOS="+goos, "GOARCH="+goarch, "CGO_ENABLED=0", "GOFLAGS=")
		out, err := cmd.CombinedOutput()
		var lines []string
		for _, l := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			if l != "" && !strings.HasPrefix(l, "#") {
				lines = append(lines, l)
			}
		}
		if err != nil || len(lines) > 0 {
			t.Errorf("%s: go vet -asmdecl: %v, %d lines, such as\n%s", target, err, len(lines), strings.Join(lines[:min(len(lines), 10)], "\n"))
		}
	}
}

// fpCase is a unified function the way the lowering leaves it, as machine
// code: frame, where the code has the Go argument area from SP, and bytes.
type fpCase struct {
	name string
	m    Meta
	code []byte
	call int // offset of a CALL rel32 to fpcallee in code, or -1
}

// fpCases cover each frame of a unified function: one that calls, so Go saves
// BP and checks the stack, a NOSPLIT leaf without a frame (NOFRAME), a NOSPLIT
// leaf with one, and a frame so large that the argument area is past an
// 8-bit displacement. Each loads its argument words, moves a local, stores
// its result words and jumps to the RET.
func fpCases() []fpCase {
	join := func(parts ...[]byte) []byte { return bytesJoin(parts) }
	jmpEnd := []byte{0xeb, 0x00}
	sig := Sig{Params: []Type{Ptr, I64, F64}, Ret: I64}
	jsv := Sig{Params: []Type{Ptr, JSV}, Ret: JSV}
	return []fpCase{
		{"fpcall", Meta{Name: "fpcall", Kind: Unified, Frame: 64, ArgBytes: 32, ArgBase: 80, Rec: &FuncRecord{Sig: sig}},
			join([]byte{0x4c, 0x8b, 0x64, 0x24, 0x50}, // mov r12, [rsp+0x50]: a0
				[]byte{0x4c, 0x8b, 0x6c, 0x24, 0x58},       // mov r13, [rsp+0x58]: a1
				[]byte{0xf2, 0x0f, 0x10, 0x44, 0x24, 0x60}, // movsd xmm0, [rsp+0x60]: a2
				[]byte{0x4c, 0x89, 0x24, 0x24},             // mov [rsp], r12: an outgoing argument
				[]byte{0xe8, 0, 0, 0, 0},                   // call fpcallee
				[]byte{0x48, 0x89, 0x44, 0x24, 0x38},       // mov [rsp+0x38], rax: a local
				[]byte{0x48, 0x89, 0x44, 0x24, 0x68},       // mov [rsp+0x68], rax: ret
				jmpEnd), 20},
		{"fpleaf", Meta{Name: "fpleaf", Kind: Unified, NoSplit: true, ArgBytes: 32, ArgBase: 8, Rec: &FuncRecord{Sig: sig}},
			join([]byte{0x4c, 0x8b, 0x64, 0x24, 0x08}, // mov r12, [rsp+8]: a0
				[]byte{0xf2, 0x0f, 0x10, 0x44, 0x24, 0x18}, // movsd xmm0, [rsp+0x18]: a2
				[]byte{0x4c, 0x89, 0x64, 0x24, 0x20},       // mov [rsp+0x20], r12: ret
				jmpEnd), -1},
		{"fpframe", Meta{Name: "fpframe", Kind: Unified, NoSplit: true, Frame: 16, ArgBytes: 48, ArgBase: 32, Rec: &FuncRecord{Sig: jsv}},
			join([]byte{0x4c, 0x8b, 0x64, 0x24, 0x20}, // mov r12, [rsp+0x20]: a0
				[]byte{0x4c, 0x8b, 0x6c, 0x24, 0x28}, // mov r13, [rsp+0x28]: a1
				[]byte{0x4c, 0x8b, 0x74, 0x24, 0x30}, // mov r14, [rsp+0x30]: a2
				[]byte{0x4c, 0x89, 0x64, 0x24, 0x08}, // mov [rsp+8], r12: a local
				[]byte{0x4c, 0x89, 0x6c, 0x24, 0x38}, // mov [rsp+0x38], r13: r0
				[]byte{0x4c, 0x89, 0x74, 0x24, 0x40}, // mov [rsp+0x40], r14: r1
				jmpEnd), -1},
		{"fpfar", Meta{Name: "fpfar", Kind: Unified, Frame: 208, ArgBytes: 32, ArgBase: 224, Rec: &FuncRecord{Sig: sig}},
			join([]byte{0x4c, 0x8b, 0xa4, 0x24, 0xe0, 0, 0, 0}, // mov r12, [rsp+0xe0]: a0
				[]byte{0xf2, 0x0f, 0x10, 0x84, 0x24, 0xf0, 0, 0, 0}, // movsd xmm0, [rsp+0xf0]: a2
				[]byte{0x4c, 0x89, 0x24, 0x24},                      // mov [rsp], r12
				[]byte{0xe8, 0, 0, 0, 0},                            // call fpcallee
				[]byte{0x48, 0x89, 0x84, 0x24, 0xf8, 0, 0, 0},       // mov [rsp+0xf8], rax: ret
				jmpEnd), 21},
	}
}

func bytesJoin(parts [][]byte) []byte {
	var out []byte
	for _, p := range parts {
		out = append(out, p...)
	}
	return out
}

// emitFP emits c through emitFunc, as Emit does.
func emitFP(c fpCase) (string, error) {
	o := &object{code: c.code, calls: map[uint64]string{}, refs: map[uint64]objRef{}}
	if c.call >= 0 {
		o.calls[uint64(c.call)] = "fpcallee"
	}
	fp, err := fpArgsOf(c.m)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(funcHeader(c.m.Name, c.m))
	b.WriteString("\tPCALIGN $16\n")
	if err := emitFunc(&b, o, 0, len(c.code), NameMap{"fpcallee": "fpcallee"}, fp); err != nil {
		return "", err
	}
	b.WriteString("\tRET\n\n")
	return b.String(), nil
}

// TestEmitFPMoves: emit writes each load of an argument word and each store
// of a result word by name through FP, and every other instruction as bytes.
func TestEmitFPMoves(t *testing.T) {
	want := map[string][]string{
		"fpcall":  {"\tMOVQ a0+0(FP), R12\n", "\tMOVQ a1+8(FP), R13\n", "\tMOVSD a2+16(FP), X0\n", "\tCALL ·fpcallee(SB)\n", "\tMOVQ AX, ret+24(FP)\n"},
		"fpleaf":  {"TEXT ·fpleaf(SB), NOSPLIT|NOFRAME, $0-32\n", "\tMOVQ a0+0(FP), R12\n", "\tMOVSD a2+16(FP), X0\n", "\tMOVQ R12, ret+24(FP)\n"},
		"fpframe": {"\tMOVQ a0+0(FP), R12\n", "\tMOVQ a1+8(FP), R13\n", "\tMOVQ a2+16(FP), R14\n", "\tMOVQ R13, r0+24(FP)\n", "\tMOVQ R14, r1+32(FP)\n"},
		"fpfar":   {"\tMOVQ a0+0(FP), R12\n", "\tMOVSD a2+16(FP), X0\n", "\tMOVQ AX, ret+24(FP)\n"},
	}
	for _, c := range fpCases() {
		text, err := emitFP(c)
		if err != nil {
			t.Fatalf("%s: %v", c.name, err)
		}
		at := 0
		for _, w := range want[c.name] {
			i := strings.Index(text[at:], w)
			if i < 0 {
				t.Fatalf("%s: no %q in order in\n%s", c.name, w, text)
			}
			at += i + len(w)
		}
		if strings.Contains(text, "(SP)") && !strings.Contains(text, "LEAQ -12288(SP), R12") {
			t.Errorf("%s: an SP operand Go writes:\n%s", c.name, text)
		}
	}
	// Anything else that reaches above the frame from SP is refused.
	base := fpCases()[0]
	for _, c := range []struct {
		code []byte
		want string
	}{
		{[]byte{0x48, 0x8b, 0x44, 0x24, 0x48}, "saved base pointer or return address"},     // mov rax, [rsp+0x48]
		{[]byte{0x48, 0x8b, 0x44, 0x24, 0x40}, "saved base pointer or return address"},     // mov rax, [rsp+0x40]
		{[]byte{0x48, 0x03, 0x44, 0x24, 0x50}, "no 8-byte move"},                           // add rax, [rsp+0x50]
		{[]byte{0x8b, 0x44, 0x24, 0x50}, "no 8-byte move"},                                 // mov eax, [rsp+0x50]
		{[]byte{0x48, 0x8b, 0x44, 0x0c, 0x50}, "no 8-byte move"},                           // mov rax, [rsp+rcx+0x50]
		{[]byte{0x48, 0x89, 0x44, 0x24, 0x50}, "no result word at 0"},                      // mov [rsp+0x50], rax
		{[]byte{0x48, 0x8b, 0x44, 0x24, 0x68}, "no argument word at 24"},                   // mov rax, [rsp+0x68]
		{[]byte{0x48, 0x8b, 0x44, 0x24, 0x54}, "no argument word at 4"},                    // mov rax, [rsp+0x54]
		{[]byte{0xf2, 0x0f, 0x10, 0x44, 0x24, 0x50}, "through the wrong kind of register"}, // movsd xmm0, [rsp+0x50]
		{[]byte{0x48, 0x8b, 0x44, 0x24, 0x60}, "through the wrong kind of register"},       // mov rax, [rsp+0x60]
		{[]byte{0xf2, 0x0f, 0x11, 0x44, 0x24, 0x68}, "through the wrong kind of register"}, // movsd [rsp+0x68], xmm0
	} {
		bad := base
		bad.code, bad.call = c.code, -1
		if _, err := emitFP(bad); err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("% x: %v, want an error with %q", c.code, err, c.want)
		}
	}
	// A register-entry leaf has no argument area: its own frame is all it
	// reaches.
	if fp, err := fpArgsOf(Meta{Name: "leaf", Kind: Register, Frame: 8}); fp != nil || err != nil {
		t.Errorf("a register-entry leaf: %v %v", fp, err)
	}
	if _, err := fpArgsOf(Meta{Name: "f", Kind: Unified, Frame: 64, ArgBase: 64, Rec: &FuncRecord{}}); err == nil {
		t.Errorf("an argument area inside the frame is taken")
	}
}

// TestFPMovesAssembleAsLowered: the Go assembler encodes the moves emit writes
// by name to the bytes the lowered text had, on each system of amd64 (windows
// has the room check before the body), so the machine code is the code the
// post-link check compares: the cases are built into a program with go build
// and their bodies read from the binary.
func TestFPMovesAssembleAsLowered(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go build")
	}
	dir := t.TempDir()
	var asm, decls strings.Builder
	asm.WriteString("#include \"textflag.h\"\n#include \"funcdata.h\"\n\n")
	decls.WriteString("package main\n\nfunc fpcallee()\n\n")
	cases := fpCases()
	for _, c := range cases {
		text, err := emitFP(c)
		if err != nil {
			t.Fatal(err)
		}
		asm.WriteString(text)
		decls.WriteString(GoDecl(c.name, c.m.Rec.Sig))
	}
	asm.WriteString("TEXT ·fpcallee(SB), NOSPLIT, $0-0\n\tRET\n\n")
	asm.WriteString(roomFunc())
	files := map[string]string{
		"go.mod":          "module fpmoves\n\ngo 1.22\n",
		"f_amd64.s":       asm.String(),
		"decl.go":         decls.String(),
		"room_windows.go": "package main\n\nfunc goasm_room()\n",
		"main.go": "package main\n\nvar keep = []any{" + func() string {
			var ns []string
			for _, c := range cases {
				ns = append(ns, c.name)
			}
			return strings.Join(ns, ", ")
		}() + "}\n\nfunc main() { println(len(keep)) }\n",
	}
	for name, text := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, goos := range []string{"linux", "darwin", "windows"} {
		bin := filepath.Join(dir, "bin-"+goos)
		cmd := exec.Command("go", "build", "-o", bin, ".")
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "GOOS="+goos, "GOARCH=amd64", "CGO_ENABLED=0", "GOWORK=off", "GOFLAGS=")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("%s: go build: %v\n%s", goos, err, out)
		}
		b := openTestBin(t, bin, "amd64")
		for _, c := range cases {
			s, ok := b.abi0("main", c.name)
			if !ok {
				t.Fatalf("%s: %s not in the binary", goos, c.name)
			}
			code, err := b.read(s.Value, int(s.Size))
			if err != nil {
				t.Fatal(err)
			}
			// The body starts on 16 bytes after Go's prologue, and the CALL
			// is the only rel32 the linker writes.
			want := append([]byte(nil), c.code...)
			at := -1
			for i := 0; i+len(want) <= len(code); i++ {
				if (s.Value+uint64(i))%16 != 0 {
					continue
				}
				got := append([]byte(nil), code[i:i+len(want)]...)
				if c.call >= 0 {
					copy(got[c.call+1:c.call+5], want[c.call+1:c.call+5])
				}
				if string(got) == string(want) {
					at = i
					break
				}
			}
			if at < 0 {
				t.Errorf("%s: the body of %s is not in the binary as lowered:\nwant % x\nin   % x", goos, c.name, want, code)
			}
		}
	}
}
