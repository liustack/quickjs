"""Write lib/goasm_helpers.txt: the C helpers prepare.py compiles into the
interpreter, which TestGoasmCoversHelperRules of internal/fixlib reads.

    python3 helpers.py INLINE_JSON OUT
"""
import json,re,sys

HEADER='''# Generated by internal/goasm/build.py. Do not edit.
# Copyright (c) 2026 The slowjs Authors.
# SPDX-License-Identifier: MIT
# See LICENSE-MIT at the repository root.
# The C helpers the goasm interpreter compiles in, one a line. A change of
# internal/fixlib to the Go copy of one of them does not reach the assembly,
# so TestGoasmCoversHelperRules of internal/fixlib asks for a row for it.
'''

def text(names):
 names=sorted(set(names))
 if not names:raise ValueError('no helpers')
 for n in names:
  if not re.fullmatch(r'[A-Za-z_]\w*',n):raise ValueError('not a C name: '+repr(n))
 return HEADER+''.join(n+'\n' for n in names)

if __name__=='__main__':
 with open(sys.argv[1]) as f:names=json.load(f)
 with open(sys.argv[2],'w') as f:f.write(text(names))
