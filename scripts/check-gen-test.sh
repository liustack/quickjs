# Test that check-gen.sh shows the profile lines of the generator (the lines
# that start with "warning: profile:" and "profile:", the stale list of
# docs/releasing.md) also when the check passes, and shows them once when it
# fails. It runs check-gen.sh in a folder of its own with a stand-in for
# gen-engine.sh, so it needs no LLVM.
#
#   scripts/check-gen-test.sh
set -eu
here=$(cd "$(dirname "$0")" && pwd)
d=$(mktemp -d)
trap 'rm -rf "$d"' EXIT

mkdir -p "$d/scripts" "$d/internal/cengine"
cp "$here/check-gen.sh" "$d/scripts/check-gen.sh"
printf '#!/bin/sh\nexit 0\n' > "$d/scripts/go-versions-test.sh"
# The stand-in writes one generated file for the architecture it is given and
# the log lines of a generator that found a stale profile.
cat > "$d/scripts/gen-engine.sh" <<'EOS'
#!/bin/sh
mkdir -p "$GEN_OUT"
printf '// Code generated by the stand-in. DO NOT EDIT.\n' > "$GEN_OUT/engine_$1.s"
echo "profile engine/pgo/profile.txt: 2729 functions, 1 whose C changed since (no profile used: JS_RegvmRun), 0 new ()"
echo "warning: profile: JS_RegvmRun has no profile, its C changed since the training"
echo "profile: 2 likely() or unlikely() of the C the training ran the other way"
[ -z "${GEN_FAIL:-}" ] || { echo "stand-in generator failed" >&2; exit 1; }
echo "an unrelated line of the generator"
EOS
chmod +x "$d/scripts/"*.sh
cd "$d"
git init -q .
for a in amd64 arm64; do
	printf '// Code generated by the stand-in. DO NOT EDIT.\n' > "internal/cengine/engine_$a.s"
done
git add .

check() { # check NAME EXPECT(pass|fail) COUNT: the stale line appears COUNT times per architecture
	set +e
	"$d/scripts/check-gen.sh" > "$d/out" 2> "$d/err"
	rc=$?
	set -e
	if [ "$2" = pass ] && [ "$rc" -ne 0 ]; then echo "check-gen-test: $1: should pass, got $rc"; cat "$d/err"; exit 1; fi
	if [ "$2" = fail ] && [ "$rc" -eq 0 ]; then echo "check-gen-test: $1: should fail, passed"; exit 1; fi
	n=$(cat "$d/out" "$d/err" | grep -c 'warning: profile: JS_RegvmRun has no profile') || true
	if [ "$n" -ne "$3" ]; then
		echo "check-gen-test: $1: the stale line shows $n times, want $3"
		cat "$d/out" "$d/err"
		exit 1
	fi
	m=$(cat "$d/out" "$d/err" | grep -c "whose C changed since (no profile used: JS_RegvmRun)") || true
	if [ "$m" -ne "$3" ]; then
		echo "check-gen-test: $1: the summary line shows $m times, want $3"
		cat "$d/out" "$d/err"
		exit 1
	fi
	if cat "$d/out" "$d/err" | grep -q 'an unrelated line'; then
		echo "check-gen-test: $1: a line that is no profile line shows"
		exit 1
	fi
	echo "check-gen-test: $1: $2, the stale line shows $n times, as expected"
}

# Both architectures print the lines, whether or not the check passes.
check "the files are what the generator makes" pass 2
# A generated file that differs fails the check and still shows the lines once per architecture.
printf '// Code generated by the stand-in. DO NOT EDIT.\n// old\n' > internal/cengine/engine_amd64.s
git add internal/cengine
check "a file differs" fail 2
# A generator that fails shows its whole log, so the lines show once (it stops at the first architecture).
GEN_FAIL=1 check "the generator fails" fail 1
