static int __attribute__((format(printf, 2, 3))) re_parse_error(REParseState *s, const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(s->u.error_msg, sizeof(s->u.error_msg), fmt, ap);
    va_end(ap);
    s->error_set = TRUE;
    return -1;
}

/* A request of memory for the code fails when the interrupt flag is set in
   the middle of the copy of a long block (lre_realloc_code), and the flag
   tells that from running out of memory. */
static int re_parse_out_of_memory(REParseState *s)
{
    if (lre_check_timeout(s->opaque))
        return re_parse_error(s, "interrupted");
    return re_parse_error(s, "out of memory");
}

/* Read the interrupt flag of the user at a step of the compile. The caller
   throws the interrupt on the message. */
static int re_poll_interrupts(REParseState *s)
{
    if (lre_check_timeout(s->opaque))
        return re_parse_error(s, "interrupted");
    return 0;
}

/* memmove of n bytes of the code. n of LRE_COPY_STEP or more are moved in
   steps of LRE_COPY_STEP bytes, with the flag read before the first and
   after each: -1 with "interrupted" set. The steps go from the end when the
   bytes move up, so that a step writes over no byte still to be moved. */
static int re_move(REParseState *s, uint8_t *dst, const uint8_t *src, size_t n)
{
    size_t off, m;

    if (n < LRE_COPY_STEP) {
        memmove(dst, src, n);
        return 0;
    }
    if (re_poll_interrupts(s))
        return -1;
    for (off = 0; off < n; off += m) {
        m = n - off < LRE_COPY_STEP ? n - off : LRE_COPY_STEP;
        if (dst > src)
            memmove(dst + n - off - m, src + n - off - m, m);
        else
            memmove(dst + off, src + off, m);
        LRE_WORK(m);
        if (re_poll_interrupts(s))
            return -1;
    }
    return 0;
}

/* insert len bytes at the position pos of the code: -1 with the error set
   (out of memory, or interrupted) */
static int re_insert(REParseState *s, int pos, int len)
{
    DynBuf *b = &s->byte_code;

    if (re_dbuf_claim(b, len, LRE_CODE_MAX))
        return re_parse_out_of_memory(s);
    if (re_move(s, b->buf + pos + len, b->buf + pos, b->size - pos))
        return -1;
    b->size += len;
    return 0;
}

/* If allow_overflow is false, return -1 in case of
   overflow. Otherwise return INT32_MAX. With allow_overflow, the digits
   can go on for any length (leading zeros, or digits past INT32_MAX): they
   are read LRE_SCAN_STEP at a time, with the interrupt flag read after each
   step and after the last, and -2 is returned with "interrupted" set. A
   number without allow_overflow ends in at most 10 digits. */
static int parse_digits(REParseState *s, const uint8_t **pp, BOOL allow_overflow)
{
    const uint8_t *p, *mark;
    uint64_t v;
    int c;

    p = mark = *pp;
    v = 0;
    for(;;) {
        c = *p;
        if (c < '0' || c > '9')
            break;
        v = v * 10 + c - '0';
        if (v >= INT32_MAX) {
            if (allow_overflow)
                v = INT32_MAX;
            else
                return -1;
        }
        p++;
        if (unlikely(p - mark >= LRE_SCAN_STEP)) {
            LRE_WORK(p - mark);
            mark = p;
            if (re_poll_interrupts(s))
                return -2;
        }
    }
    LRE_WORK(p - mark);
    if (mark != *pp && re_poll_interrupts(s))
        return -2;
    *pp = p;
    return v;
}

static int re_parse_expect(REParseState *s, const uint8_t **pp, int c)
{
    const uint8_t *p;
    p = *pp;
    if (*p != c)
        return re_parse_error(s, "expecting '%c'", c);
    p++;
    *pp = p;
    return 0;
}

/* Parse an escape sequence, *pp points after the '\':
   allow_utf16 value:
   0 : no UTF-16 escapes allowed
   1 : UTF-16 escapes allowed
   2 : UTF-16 escapes allowed and escapes of surrogate pairs are
   converted to a unicode character (unicode regexp case).

   Return the unicode char and update *pp if recognized,
   return -1 if malformed escape,
   return -2 otherwise.

   With s, the regexp parser's, the digits of \u{...}, which can go on for
   any length with leading zeros, are read LRE_SCAN_STEP at a time, with the
   interrupt flag read after each step and after the last: -3 with
   "interrupted" set. With flag instead (the parser of a script), the same
   steps read *flag, and -3 is returned when it is set. */
static int re_parse_escape(const uint8_t **pp, int allow_utf16, REParseState *s,
                           const volatile int *flag)
{
    const uint8_t *p, *mark;
    uint32_t c;

    p = *pp;
    c = *p++;
    switch(c) {
    case 'b':
        c = '\b';
        break;
    case 'f':
        c = '\f';
        break;
    case 'n':
        c = '\n';
        break;
    case 'r':
        c = '\r';
        break;
    case 't':
        c = '\t';
        break;
    case 'v':
        c = '\v';
        break;
    case 'x':
        {
            int h0, h1;

            h0 = from_hex(*p++);
            if (h0 < 0)
                return -1;
            h1 = from_hex(*p++);
            if (h1 < 0)
                return -1;
            c = (h0 << 4) | h1;
        }
        break;
    case 'u':
        {
            int h, i;
            uint32_t c1;

            if (*p == '{' && allow_utf16) {
                p++;
                mark = p;
                c = 0;
                for(;;) {
                    h = from_hex(*p++);
                    if (h < 0)
                        return -1;
                    c = (c << 4) | h;
                    if (c > 0x10FFFF)
                        return -1;
                    if (*p == '}')
                        break;
                    if ((s || flag) && unlikely(p - mark >= LRE_SCAN_STEP)) {
                        LRE_WORK(p - mark);
                        mark = p;
                        if (s ? re_poll_interrupts(s) : poll_flag(flag) != 0)
                            return -3;
                    }
                }
                if (s || flag) {
                    LRE_WORK(p - mark);
                    if (mark != *pp + 2 &&
                        (s ? re_poll_interrupts(s) : poll_flag(flag) != 0))
                        return -3;
                }
                p++;
            } else {
                c = 0;
                for(i = 0; i < 4; i++) {
                    h = from_hex(*p++);
                    if (h < 0) {
                        return -1;
                    }
                    c = (c << 4) | h;
                }
                if (is_hi_surrogate(c) &&
                    allow_utf16 == 2 && p[0] == '\\' && p[1] == 'u') {
                    /* convert an escaped surrogate pair into a
                       unicode char */
                    c1 = 0;
                    for(i = 0; i < 4; i++) {
                        h = from_hex(p[2 + i]);
                        if (h < 0)
                            break;
                        c1 = (c1 << 4) | h;
                    }
                    if (i == 4 && is_lo_surrogate(c1)) {
                        p += 6;
                        c = from_surrogate(c, c1);
                    }
                }
            }
        }
        break;
    case '0': case '1': case '2': case '3':
    case '4': case '5': case '6': case '7':
        c -= '0';
        if (allow_utf16 == 2) {
            /* only accept \0 not followed by digit */
            if (c != 0 || is_digit(*p))
                return -1;
        } else {
            /* parse a legacy octal sequence */
            uint32_t v;
            v = *p - '0';
            if (v > 7)
                break;
            c = (c << 3) | v;
            p++;
            if (c >= 32)
                break;
            v = *p - '0';
            if (v > 7)
                break;
            c = (c << 3) | v;
            p++;
        }
        break;
    default:
        return -2;
    }
    *pp = p;
    return c;
}

int lre_parse_escape(const uint8_t **pp, int allow_utf16)
{
    return re_parse_escape(pp, allow_utf16, NULL, NULL);
}

int lre_parse_escape_poll(const uint8_t **pp, int allow_utf16,
                          const volatile int *flag)
{
    return re_parse_escape(pp, allow_utf16, NULL, flag);
}

